import { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';

interface EntryResult {
  persona: string;
  date: string;
  quote: string;
  poetic_story: string;
  tags: string[];
  photos: string[];
  likes: number;
}

export default function Result() {
  const navigate = useNavigate();
  const [data, setData] = useState<EntryResult | null>(null);
  const [isSaving, setIsSaving] = useState(false);

  useEffect(() => {
    // Entry 페이지에서 저장한 결과물 불러오기
    const saved = sessionStorage.getItem('entry_result');
    if (saved) {
      setData(JSON.parse(saved));
    } else {
      alert('결과 데이터가 없습니다. 처음부터 다시 시작해주세요.');
      navigate('/');
    }
  }, [navigate]);

  if (!data) return null;

  // 서가(Shelves)에 저장하는 로직 (현재는 로컬 스토리지 활용, 추후 Supabase 연동)
  const handleSaveToShelves = () => {
    setIsSaving(true);

    // 기존 서가 데이터 불러오기 (없으면 빈 배열)
    const existingShelves = JSON.parse(localStorage.getItem('liaollet_shelves') || '[]');

    // 새 데이터 추가 (맨 앞에 추가)
    localStorage.setItem('liaollet_shelves', JSON.stringify([data, ...existingShelves]));

    // 임시 결과 삭제
    sessionStorage.removeItem('entry_result');

    setTimeout(() => {
      setIsSaving(false);
      navigate('/shelves'); // 서가 페이지로 이동
    }, 1000);
  };

  // 폐기(다시 만들기) 로직
  const handleDiscard = () => {
    if (window.confirm('이 결과물을 폐기하고 다시 만드시겠습니까?')) {
      sessionStorage.removeItem('entry_result');
      navigate('/entry');
    }
  };

  // 이미지 다운로드 로직 (단순 링크 다운로드 방식)
  const handleDownload = () => {
    if (!data.photos || data.photos.length === 0) return;
    const link = document.createElement('a');
    link.href = data.photos[0];
    link.download = `LIAOLLET_${data.persona}_${data.date.replace(/\./g, '')}.jpg`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const personaNames: Record<string, string> = {
    lia: 'LIA',
    ol: 'OL',
    let: 'LET'
  };

  return (
    <div className="min-h-screen bg-archive-bg text-archive-dark flex flex-col justify-center items-center p-4 sm:p-8 md:p-12 font-serif relative">

      {/* 헤더 */}
      <div className="w-full max-w-4xl mb-8 text-center md:text-left">
        <span className="font-mono text-xs text-archive-terracotta uppercase tracking-widest block mb-2">04. CURATED ARTWORK</span>
        <h2 className="text-3xl font-bold mb-3 text-archive-paper">완성된 아카이브 도록</h2>
        <p className="text-archive-craft text-sm">수집된 소스들이 정제된 시각적 콜라주와 담백한 해설로 재구성되었습니다.</p>
      </div>

      {/* 메인 결과 카탈로그 (종이 느낌) */}
      <div className="w-full max-w-4xl bg-[#F5F2EC] p-6 sm:p-12 shadow-[0_20px_50px_rgba(0,0,0,0.5)] relative"
           style={{ clipPath: 'polygon(0% 0.5%, 4% 0%, 9% 0.4%, 15% 0.1%, 21% 0.5%, 27% 0%, 33% 0.4%, 39% 0.1%, 45% 0.5%, 51% 0%, 57% 0.4%, 63% 0.1%, 69% 0.5%, 75% 0%, 81% 0.4%, 87% 0.1%, 93% 0.5%, 100% 0.1%, 100% 99.5%, 96% 100%, 91% 99.6%, 85% 99.9%, 79% 99.5%, 73% 100%, 67% 99.6%, 61% 100%, 55% 99.5%, 49% 99.9%, 43% 99.6%, 37% 100%, 31% 99.5%, 25% 100%, 19% 99.5%, 13% 99.9%, 7% 99.5%, 0% 99.9%)' }}>

        {/* 테이프 장식 */}
        <div className="absolute -top-3 right-20 w-24 h-6 bg-archive-craft/80 -rotate-2 shadow-sm"></div>

        {/* 상단 헤더 (날짜 & 페르소나) */}
        <div className="flex justify-between items-end border-b-2 border-archive-dark pb-4 mb-8">
          <div>
            <span className="font-mono text-[10px] text-archive-terracotta uppercase tracking-wider block mb-1">CATALOGUE PIECE</span>
            <h3 className="font-serif font-bold text-xl">{data.date} / ATTIC ARCHIVE</h3>
          </div>
          <div className="text-right">
            <span className="inline-block px-3 py-1 bg-archive-dark text-archive-paper font-mono text-[11px] uppercase font-bold tracking-widest">
              {personaNames[data.persona] || data.persona} ASPECT
            </span>
          </div>
        </div>

        {/* 이미지와 텍스트 레이아웃 (2단 구성) */}
        <div className="grid grid-cols-1 md:grid-cols-12 gap-8 mb-8">

          {/* 생성된 이미지 영역 (좌측 7칸) */}
          <div className="md:col-span-7 flex flex-col justify-center">
            <div className="bg-[#1C1A18] p-3 shadow-inner">
              {data.photos && data.photos.length > 0 ? (
                <img
                  src={data.photos[0]}
                  alt="Generated Collage"
                  className="w-full h-auto aspect-square object-contain bg-black/50"
                />
              ) : (
                <div className="w-full aspect-square flex items-center justify-center text-archive-muted">이미지가 없습니다.</div>
              )}
              <div className="flex justify-between items-center mt-2 px-1">
                <span className="font-mono text-[9px] text-archive-muted">GENERATED BY NANO BANANA</span>
                <span className="font-mono text-[9px] text-archive-muted">1:1 RATIO</span>
              </div>
            </div>
          </div>

          {/* 텍스트 영역 (우측 5칸) */}
          <div className="md:col-span-5 flex flex-col justify-between">
            <div>
              <div className="mb-6">
                <span className="font-mono text-[10px] text-archive-terracotta uppercase tracking-widest block mb-2">CURATORIAL COMMENT</span>
                <p className="text-[13px] leading-relaxed text-[#2A2825] border-l-2 border-archive-craft pl-3">
                  {data.poetic_story}
                </p>
              </div>

              <div className="mb-6">
                <span className="font-mono text-[10px] text-archive-terracotta uppercase tracking-widest block mb-2">ORIGINAL QUOTE</span>
                <p className="text-[13px] italic text-[#6E675F] bg-[#EAE5DC]/50 p-3">
                  "{data.quote}"
                </p>
              </div>
            </div>

            <div>
              <span className="font-mono text-[10px] text-archive-terracotta uppercase tracking-widest block mb-2">KEYWORDS</span>
              <div className="flex flex-wrap gap-2">
                {data.tags.map((tag, idx) => (
                  <span key={idx} className="px-2 py-1 bg-archive-dark text-archive-paper text-xs font-serif">
                    {tag}
                  </span>
                ))}
              </div>
            </div>
          </div>

        </div>

        {/* 하단 푸터 */}
        <div className="border-t border-archive-craft/60 pt-4 flex justify-between items-center font-mono text-[10px] text-archive-muted">
          <span>LIAOLLET ATTIC TASTE ARCHIVE</span>
          <span>EDITION N° {sessionStorage.getItem('ticket_no') || '000'} / 500</span>
        </div>

      </div>

      {/* 하단 액션 버튼 (저장 / 다운로드 / 폐기) */}
      <div className="w-full max-w-4xl mt-8 flex flex-col sm:flex-row justify-center gap-4">
        <button
          onClick={handleDiscard}
          className="flex-1 py-4 border border-archive-muted text-archive-craft font-mono text-sm hover:bg-archive-muted/20 transition-colors"
        >
          ✕ 폐기하고 다시 만들기
        </button>
        <button
          onClick={handleDownload}
          className="flex-1 py-4 border border-archive-craft text-archive-paper font-mono text-sm hover:bg-archive-craft/20 transition-colors flex items-center justify-center gap-2"
        >
          ↓ 이미지 다운로드
        </button>
        <button
          onClick={handleSaveToShelves}
          disabled={isSaving}
          className={`flex-[2] py-4 font-mono text-sm font-bold shadow-lg transition-all flex items-center justify-center gap-2 ${
            isSaving ? 'bg-archive-muted text-archive-dark cursor-wait' : 'bg-archive-paper text-archive-dark hover:bg-white'
          }`}
        >
          {isSaving ? '서가에 보관 중...' : '취향의 서가에 저장하기 →'}
        </button>
      </div>

    </div>
  );
}